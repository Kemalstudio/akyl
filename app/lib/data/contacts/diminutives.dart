  static String _key(String s) => s.toLowerCase().replaceAll('ё', 'е').trim();

  /// Как ещё могут назвать этот контакт.
  static List<String> variantsOf(String canonical) =>
      _map[_key(canonical)] ?? const [];

  /// Полные имена, для которых это слово — краткая форма.
  /// «саша» -> [александр, александра]
  static List<String> expandsTo(String spoken) {
    final s = _key(spoken);
    final out = <String>[];
    _map.forEach((full, shorts) {
      if (shorts.contains(s)) out.add(full);
    });
    return out;
  }

  static Iterable<String> get knownFullNames => _map.keys;
}
