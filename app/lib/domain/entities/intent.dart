/// Намерения, которые Akyl понимает в v1.0 (ТЗ, FR-3).
enum Intent {
  /// «позвони маме», «набери Ахмеда на рабочий»
  call,

  /// «напиши Мерет что я опаздываю»
  sms,

  /// «да», «отправь», «давай» — подтверждение отложенного действия
  confirm,

  /// «отмена», «стоп», «не надо»
  cancel,

  /// «первому», «брату» — выбор из предложенного списка
  select,

  /// фраза не распознана как команда
  unknown,
}

/// Слоты, которые NLU извлекает из фразы (ТЗ, FR-4).
enum Slot {
  /// имя контакта в том виде, как его произнесли: «маме», «Ахмеду»
  contact,

  /// мобильный | рабочий | домашний
  phoneType,

  /// текст SMS
  message,

  /// «по громкой связи» — звук в динамик, а не в трубку
  speaker,

  /// сырой текст выбора для Intent.select: «первому», «брату»
  choice,
}

/// Тип номера телефона. Значения совпадают с ContactsContract на стороне Kotlin.
enum PhoneType {
  mobile,
  work,
  home,
  other;

  /// Как произнести тип вслух в ответе TTS.
  String get spokenRu => switch (this) {
        PhoneType.mobile => 'мобильный',
        PhoneType.work => 'рабочий',
        PhoneType.home => 'домашний',
        PhoneType.other => 'другой',
      };
}
