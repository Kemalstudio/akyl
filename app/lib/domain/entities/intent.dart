/// Намерения, которые Akyl понимает в v1.0 (ТЗ, FR-3).
enum Intent {
  /// «позвони маме», «набери Ахмеда на рабочий»
  call,

  /// «напиши Мерет что я опаздываю»
  sms,

  /// «да», «отправь», «давай» — подтверждение отложенного действия
  confirm,

  /// «отмена», «стоп», «не надо»
  cancel,

  /// «первому», «брату» — выбор из предложенного списка
  select,

  /// «скажи время», «который час»
  time,

  /// «какое сегодня число»
  date,

  /// «сколько заряда»
  battery,

  /// Короткий разговор: «как дела», «спасибо».
  smallTalk,

  /// «поставь будильник на 7:30»
  alarm,

  /// «поставь таймер на 5 минут»
  timer,

  /// «включи фонарик», «выключи фонарик»
  flashlight,

  /// «громче», «тише», «выключи звук»
  volume,

  /// «прочитай последнее сообщение»
  readSms,

  /// «кто звонил», «пропущенные звонки»
  recentCalls,

  /// «открой ватсап»
  openApp,

  /// «повтори» — сказать последний ответ ещё раз
  repeat,

  /// «нет, не ему, а Ахмеду-брату» — повторить команду с другим адресатом
  correct,

  /// «запомни: ключи от гаража у Ахмеда»
  remember,

  /// «где ключи от гаража», «что ты помнишь»
  recall,

  /// «забудь про ключи»
  forget,

  /// «когда я последний раз звонил папе»
  lastCall,

  /// «напоминай каждый день в 9 утра выпить таблетку»
  remind,

  /// «какие у меня напоминания»
  listReminders,

  /// «удали напоминание про таблетку»
  cancelReminder,

  /// «помогите», «мне плохо» — звонок и SMS близким с местом
  sos,

  /// фраза не распознана как команда
  unknown,
}

/// Слоты, которые NLU извлекает из фразы (ТЗ, FR-4).
enum Slot {
  /// имя контакта в том виде, как его произнесли: «маме», «Ахмеду»
  contact,

  /// мобильный | рабочий | домашний
  phoneType,

  /// текст SMS
  message,

  /// «по громкой связи» — звук в динамик, а не в трубку
  speaker,

  /// сырой текст выбора для Intent.select: «первому», «брату»
  choice,

  /// ID explicitly selected by the user, independent of duplicate names.
  contactId,

  topic,

  /// Значение команды устройства: «07:30», секунды таймера, «on»/«off»,
  /// «up»/«down»/«mute»/«max», название приложения.
  value,
}

/// Тип номера телефона. Значения совпадают с ContactsContract на стороне Kotlin.
enum PhoneType {
  mobile,
  work,
  home,
  other;

  /// Как произнести тип вслух в ответе TTS.
  String get spokenRu => switch (this) {
    PhoneType.mobile => 'мобильный',
    PhoneType.work => 'рабочий',
    PhoneType.home => 'домашний',
    PhoneType.other => 'другой',
  };
}
